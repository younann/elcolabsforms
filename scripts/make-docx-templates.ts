// writes server/docx-templates.gen.ts from the original forms in files/ (run again after replacing an original)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { FORMS } from '../shared/forms';

const root = new URL('../', import.meta.url);

// original file per form id
const MATCH: Record<string, string> = {
  f1220: 'T-20001-1',
  f536: 'T-20004-5',
  detectors: 'גלאים עצמאיים',
  aerosol: 'בארוסול',
  gas: 'בגז',
};

const names = readdirSync(new URL('files/', root)).map((n) => n.normalize('NFC'));
const out: string[] = [];
for (const def of FORMS) {
  const hits = names.filter((n) => n.endsWith('.docx') && n.includes(MATCH[def.id]));
  if (hits.length !== 1) throw new Error(`${def.id}: expected one original, found ${hits.length}`);
  const b64 = readFileSync(new URL(`files/${hits[0]}`, root)).toString('base64');
  out.push(`  ${JSON.stringify(`${def.id}:${def.version}`)}: ${JSON.stringify(b64)},`);
  console.log(def.id, hits[0]);
}

writeFileSync(
  new URL('server/docx-templates.gen.ts', root),
  `// generated by scripts/make-docx-templates.ts, do not edit\n// original forms keyed by "formId:version", base64\nexport const DOCX_TEMPLATES: Record<string, string> = {\n${out.join('\n')}\n};\n`,
);
console.log('wrote server/docx-templates.gen.ts');
