// writes shared/pdf/assets.gen.ts (print.css + Heebo font) so functions need no file reads
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);
const css = readFileSync(new URL('shared/pdf/print.css', root), 'utf8');

// hebrew + latin subsets, as in @fontsource/heebo
const ranges: Record<string, string> = {
  hebrew: 'U+0307-0308,U+0590-05FF,U+200C-2010,U+20AA,U+25CC,U+FB1D-FB4F',
  latin:
    'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
};
const faces: string[] = [];
for (const subset of Object.keys(ranges)) {
  for (const weight of [400, 700]) {
    const file = require.resolve(`@fontsource/heebo/files/heebo-${subset}-${weight}-normal.woff2`);
    const b64 = readFileSync(file).toString('base64');
    faces.push(
      `@font-face{font-family:'Heebo';font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${b64}) format('woff2');unicode-range:${ranges[subset]};}`,
    );
  }
}

const out = `// generated by scripts/gen-pdf-assets.ts, do not edit
export const PRINT_CSS = ${JSON.stringify(css)};
export const FONT_CSS = ${JSON.stringify(faces.join('\n'))};
`;
writeFileSync(new URL('shared/pdf/assets.gen.ts', root), out);
console.log('wrote shared/pdf/assets.gen.ts', out.length, 'bytes');
